def patch(fn, pairs):
    global tot
    p = os.path.join(B, fn)
    t = open(p, encoding='utf-8').read()
    for i, (a, b) in enumerate(pairs):
        if a not in t:
            print('  [未命中] %s #%d  %s' % (fn, i + 1, a[:55].replace('\n', '|')))
            continue
