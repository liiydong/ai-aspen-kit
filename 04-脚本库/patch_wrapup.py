import sys, os
sys.stdout.reconfigure(encoding='utf-8')
B = r'D:\obsidian-vault\毕业设计\化学法版'
tot = 0


def patch(fn, pairs):
    global tot
    p = os.path.join(B, fn)
    t = open(p, encoding='utf-8').read()
    for i, (a, b) in enumerate(pairs):
        if a not in t:
            print('  [未命中] %s #%d  %s' % (fn, i + 1, a[:55].replace('\n', '|')))
            continue
        t = t.replace(a, b)
        tot += 1
        print('  [OK] %s #%d  %s' % (fn, i + 1, a[:44].replace('\n', '|')))
    open(p, 'w', encoding='utf-8').write(t)


