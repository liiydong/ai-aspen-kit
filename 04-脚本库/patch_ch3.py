# ---------- 7) 表号重编（按出现顺序 3-1..3-13） ----------
titles = []
for m in re.finditer(r'^表\s*3-(\d+)\s', t, re.M):
    titles.append((m.start(), m.group(1)))
# 建立 旧号 -> 新号（按第一次作为表题出现）
order = []
for pos, num in titles:
    order.append(num)
uniq = []
for n in order:
    if n not in uniq:
        uniq.append(n)
mapping = {old: str(i + 1) for i, old in enumerate(uniq)}
LOG.append('表号映射: %s' % mapping)
# 用占位符两段替换
def ph(m):
    old = m.group(1)
    return '表\x01%02d\x01' % (int(mapping.get(old, old)) if old in mapping else int(old))
t = re.sub(r'表\s*3-(\d+)', ph, t)
t = re.sub(r'表\x01(\d+)\x01', lambda m: '表 3-%d' % int(m.group(1)), t)
