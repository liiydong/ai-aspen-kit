def patch(path, pairs):
    x = open(path, encoding='utf-8').read()
    ok = 0
    for old, new in pairs:
        if old in x:
            x = x.replace(old, new, 1)
            ok += 1
        else:
            print('  MISS: %s' % old[:70])
    open(path, 'w', encoding='utf-8').write(x)
    print('  %-40s 命中 %d/%d' % (os.path.basename(path), ok, len(pairs)))


