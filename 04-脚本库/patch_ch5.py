def rep(old, new, desc):
    global t
    n = t.count(old)
    if n != 1:
        LOG.append('!! 失败(%d处): %s' % (n, desc)); return False
    t = t.replace(old, new, 1); LOG.append('OK  %s' % desc); return True

def rep_block(title, new_block, desc):
    global t
    i = t.find(title)
    if i < 0:
        LOG.append('!! 未找到: %s' % desc); return False
    j = t.find('\n', i); k = j + 1
    while True:
        m = re.match(r'\|.*\n', t[k:])
        if not m:
            break
        k += m.end()
    t = t[:i] + title + '\n\n' + new_block + t[k:]
    LOG.append('OK  整表替换: %s' % desc); return True

