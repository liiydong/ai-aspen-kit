def patch(fn, pairs):
    global n_changes
    p = os.path.join(BASE, fn)
    t = open(p, encoding='utf-8').read()
    for i, (a, b) in enumerate(pairs):
        if a not in t:
            print('  [未命中] %s #%d  %s' % (fn, i + 1, a[:60].replace('\n', '|')))
            continue
        c = t.count(a)
        t = t.replace(a, b)
        n_changes += 1
        print('  [OK] %s #%d  (%d 处)  %s' % (fn, i + 1, c, a[:40].replace('\n', '|')))
    open(p, 'w', encoding='utf-8').write(t)


